    /// <summary>
    /// Livelli con un numero fisso anche finché mancano livelli nuovi prima di loro (dalla 0.81: l'esame finale di Toni
    /// è sempre il 275, non l'ultimo). Con tutti i 300 livelli pronti coincide con la posizione della roadmap.
    /// </summary>
    static readonly (string id, int number)[] PinnedLevels = { ("toni_final_exam", 275) };

    /// <summary>Livelli costruiti ma fuori dalla progressione (bonus stagionali): il prefab resta, il catalogo no.</summary>
    static readonly string[] BonusLevels = { "hw_werepug" };

    static List<LevelDefinition> ApplyRoadmapOrder(List<LevelDefinition> built, out List<LevelDefinition> bonus)
    {
        var byId = new Dictionary<string, LevelDefinition>();
        foreach (LevelDefinition d in built)
            if (d != null && !byId.ContainsKey(d.levelId)) byId.Add(d.levelId, d);
        var ordered = new List<LevelDefinition>();
        var used = new HashSet<string>();
        int missing = 0;
        foreach (string id in RoadmapOrder)
        {
            if (byId.TryGetValue(id, out LevelDefinition d)) { ordered.Add(d); used.Add(id); }
            else missing++;
        }
        bonus = new List<LevelDefinition>();
        foreach (string id in BonusLevels)
            if (byId.TryGetValue(id, out LevelDefinition d)) { bonus.Add(d); used.Add(id); }
        foreach (LevelDefinition d in built)
            if (d != null && !used.Contains(d.levelId))
            {
                Debug.LogWarning("[Gotcha] Livello " + d.levelId + " non è nella roadmap (GotchaLevelOrder.cs): messo in fondo.");
                ordered.Add(d);
                used.Add(d.levelId);
            }
        foreach ((string id, int number) pin in PinnedLevels)
        {
            int at = ordered.FindIndex(d => d.levelId == pin.id);
            if (at < 0) continue;
            LevelDefinition d0 = ordered[at];
            ordered.RemoveAt(at);
            ordered.Insert(Mathf.Clamp(pin.number - 1, 0, ordered.Count), d0);
        }
        if (missing > 0) Debug.Log("[Gotcha] Roadmap: " + ordered.Count + " livelli in gioco, " + missing + " livelli nuovi ancora da fare (saltati).");
        return ordered;
    }
